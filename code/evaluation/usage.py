"""Write code/evaluation/usage_report.md from the full-dataset run that produced output.csv."""
from datetime import datetime, timezone
from pathlib import Path

from audit.llm import EFFORT, PRICES

REPORT = Path(__file__).with_name("usage_report.md")


def write_usage_report(info, requests=518):
    usage = info["usage"]
    lines = [
        "# Usage report",
        "",
        f"Generated by `python3 code/main.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
        f"Run: `{info['requests_file']}` -> {info['rows']} rows in output.csv, {info['seconds']} s wall clock.",
        f"Claude available during the run: {'yes' if info['llm_online'] else 'no (rules decided intent)'}.",
        "",
        "## Where models are used",
        "",
        "| Stage | Model use |",
        "| --- | --- |",
        "| Request intent (deletion vs not, any language) | Claude, one structured-output call per distinct request text; multilingual rules as fallback and cross-check |",
        "| Evidence parsing, identity resolution, job attribution, policy, step planning | Deterministic Python, no model calls |",
        "| Screenshot text | Local OCR (macOS Vision) at build time, cached in `code/cache/media/`; no model tokens |",
        "",
        "Calls are cached on disk (`code/cache/llm_cache.json`) by model, prompt version and input text, so a",
        "re-run spends nothing. Token counts below are the usage of the API calls behind every verdict used in",
        "this run, whether the call happened now or was served from that cache.",
        "",
        "## Totals",
        "",
        "| Provider | Model | Effort | API calls this run | Served from cache | Input tokens | Output tokens | Total tokens | Est. cost (USD) |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    tot_calls = tot_cached = tot_in = tot_out = 0
    tot_cost = 0.0
    for model, m in sorted(usage.items()):
        tokens = m["input_tokens"] + m["output_tokens"]
        lines.append(f"| Anthropic | `{model}` | {EFFORT} | {m['calls']} | {m['cached']} | {m['input_tokens']:,} | "
                     f"{m['output_tokens']:,} | {tokens:,} | ${m['cost_usd']:.4f} |")
        tot_calls += m["calls"]
        tot_cached += m["cached"]
        tot_in += m["input_tokens"]
        tot_out += m["output_tokens"]
        tot_cost += m["cost_usd"]
    if not usage:
        lines.append("| Anthropic | (none: offline run) | - | 0 | 0 | 0 | 0 | 0 | $0.0000 |")
    lines.append(f"| **Overall** | | | **{tot_calls}** | **{tot_cached}** | **{tot_in:,}** | **{tot_out:,}** | "
                 f"**{tot_in + tot_out:,}** | **${tot_cost:.4f}** |")
    lines += [
        "",
        "## Per request",
        "",
        f"- Requests in output.csv: {requests}",
        f"- Average tokens per request: {(tot_in + tot_out) / requests:.1f} "
        f"({tot_in / requests:.1f} input, {tot_out / requests:.1f} output)",
        f"- Estimated cost per request: ${tot_cost / requests:.6f}",
        f"- Estimated total cost: ${tot_cost:.4f}",
        "",
        "Intent is classified for the 518 evaluation requests and the 32 sample requests, because both sets share",
        "deletion-job batches in the activity stream and the job linker must know which requests started a job.",
        "Averages divide the whole run's usage by the 518 evaluation requests.",
        "",
        "## Pricing used",
        "",
        "| Model | Input $/1M tokens | Output $/1M tokens |",
        "| --- | ---: | ---: |",
    ]
    for model, (p_in, p_out) in PRICES.items():
        lines.append(f"| `{model}` | ${p_in:.2f} | ${p_out:.2f} |")
    lines += [
        "",
        "Anthropic first-party API list prices. Output tokens include the model's thinking tokens.",
        "",
        f"Rule/model intent disagreements in this run: {', '.join(info['intent_disagreements']) or 'none'}.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    return REPORT
