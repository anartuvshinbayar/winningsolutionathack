"""Write code/evaluation/usage_report.md from the full-dataset run that produced output.csv."""
from datetime import datetime, timezone
from pathlib import Path

from audit.intent import BATCH_SIZE
from audit.llm import EFFORT, FREE_TIER, GEMINI_MODEL, GEMINI_THINKING_LEVEL, PRICES

REPORT = Path(__file__).with_name("usage_report.md")
PROVIDER_LABEL = {"anthropic": "Anthropic", "gemini": "Google (Gemini API)"}
KEY_NAME = {"anthropic": "ANTHROPIC_API_KEY", "gemini": "GEMINI_API_KEY"}


def write_usage_report(info, requests=518):
    usage = info["usage"]
    configured = info.get("llm_provider")
    if configured:
        model_line = (f"Model configured for the run: {PROVIDER_LABEL[configured]} `{info['llm_model']}` "
                      f"({KEY_NAME[configured]} set).")
    else:
        model_line = "Model configured for the run: none (no ANTHROPIC_API_KEY or GEMINI_API_KEY)."
    lines = [
        "# Usage report",
        "",
        f"Generated by `python3 code/main.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
        f"Run: `{info['requests_file']}` -> {info['rows']} rows in output.csv, {info['seconds']} s wall clock.",
        model_line,
        f"Intent verdicts from the model: {info.get('intent_decided', 0)} of {info.get('intent_distinct', 0)} distinct "
        "request texts; the multilingual rules decided the rest.",
        f"Screenshot and PDF readings used: {info.get('media_readings', 0)} of {info.get('media_files', 0)} files, read by "
        f"`{info.get('media_model')}` (cached in `code/cache/media/`).",
        "",
        "## Where models are used",
        "",
        "| Stage | Model use |",
        "| --- | --- |",
        "| Request intent (deletion vs not, any language) | Claude when `ANTHROPIC_API_KEY` is set, else Gemini "
        f"(`{GEMINI_MODEL}`) when `GEMINI_API_KEY` is set: structured-output calls of up to {BATCH_SIZE} distinct request texts each. "
        "Multilingual rules are the fallback and cross-check every model verdict |",
        "| Evidence parsing, identity resolution, job attribution, policy, step planning | Deterministic Python, no model calls |",
        f"| Screenshots and PDFs | `{info.get('media_model')}` reads each file once, sent inline, with "
        "`code/tools/extract_media.py`: every visible record as JSON (system, resource id, category, identifiers, "
        "state, timestamps). Answers and their token usage are cached in `code/cache/media/<evidence_id>.json` |",
        "",
        "Intent answers are cached in `code/cache/llm_cache.json` per model, prompt version and request text, and",
        "screenshot/PDF readings in `code/cache/media/`, each with the usage of the call that produced it, so a",
        "re-run spends nothing. Token counts below are the usage of the API calls behind every answer used in this",
        "run, whether the call happened now or was served from those caches.",
        "",
        "## Totals",
        "",
        "| Provider | Model | Use | API calls this run | Calls served from cache | Input tokens | Output tokens | "
        "Thinking tokens | Total tokens | Est. cost at list price (USD) |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    tot = {"calls": 0, "cached": 0, "input_tokens": 0, "output_tokens": 0, "thinking_tokens": 0, "cost_usd": 0.0}
    for m in usage:
        tokens = m["input_tokens"] + m["output_tokens"] + m["thinking_tokens"]
        thinking = f"{m['thinking_tokens']:,}" if m["provider"] == "gemini" else "in output"
        lines.append(f"| {PROVIDER_LABEL.get(m['provider'], m['provider'])} | `{m['model']}` | {m['use']} | {m['calls']} | "
                     f"{m['cached']} | {m['input_tokens']:,} | {m['output_tokens']:,} | {thinking} | {tokens:,} | "
                     f"${m['cost_usd']:.4f} |")
        for k in tot:
            tot[k] += m[k]
    if not usage:
        lines.append("| - | (none: no model key, rules decided intent) | - | 0 | 0 | 0 | 0 | 0 | 0 | $0.0000 |")
    total_tokens = tot["input_tokens"] + tot["output_tokens"] + tot["thinking_tokens"]
    lines.append(f"| **Overall** | | | **{tot['calls']}** | **{tot['cached']}** | **{tot['input_tokens']:,}** | "
                 f"**{tot['output_tokens']:,}** | **{tot['thinking_tokens']:,}** | **{total_tokens:,}** | "
                 f"**${tot['cost_usd']:.4f}** |")
    free = sorted({m["model"] for m in usage if m["model"] in FREE_TIER})
    lines += [
        "",
        "## Per request",
        "",
        f"- Requests in output.csv: {requests}",
        f"- Average tokens per request: {total_tokens / requests:.1f} ({tot['input_tokens'] / requests:.1f} input, "
        f"{tot['output_tokens'] / requests:.1f} output, {tot['thinking_tokens'] / requests:.1f} thinking)",
        f"- Estimated cost per request at list price: ${tot['cost_usd'] / requests:.6f}",
        f"- Estimated total cost at list price: ${tot['cost_usd']:.4f}",
    ]
    if free:
        lines.append(f"- Billed on the Gemini API free tier, which this key uses: $0.00 for {', '.join(f'`{m}`' for m in free)}")
    lines += [
        "",
        "Intent is classified for the 518 evaluation requests and the 32 sample requests, because both sets share",
        "deletion-job batches in the activity stream and the job linker must know which requests started a job.",
        "The 550 requests hold 398 distinct texts, and each distinct text is classified once. Averages divide the",
        "whole run's usage by the 518 evaluation requests.",
        "",
        "## Pricing used",
        "",
        "| Provider | Model | Input $/1M tokens | Output $/1M tokens (incl. thinking) |",
        "| --- | --- | ---: | ---: |",
    ]
    for model, (p_in, p_out) in PRICES.items():
        provider = "Google (Gemini API)" if model.startswith("gemini") else "Anthropic"
        lines.append(f"| {provider} | `{model}` | ${p_in:.2f} | ${p_out:.2f} |")
    lines += [
        "",
        "Anthropic first-party list prices; Claude runs at effort `" + EFFORT + "` and counts thinking inside its output",
        "tokens. Gemini prices are the Gemini API paid-tier standard list prices (ai.google.dev/gemini-api/docs/pricing,",
        "checked 2026-10-25); Google lists `gemini-3.8-flash` at these rates through 2026-12-31 and at $1.50 / $7.50 from",
        f"2027-01-01. Gemini reports thinking separately (`thoughtsTokenCount`, thinking level `{GEMINI_THINKING_LEVEL}`) and",
        "bills it at the output rate. The Gemini API free tier bills $0; the estimates above show what the same tokens",
        "would cost on the paid tier.",
        "",
        f"Rule/model intent disagreements in this run: {', '.join(info['intent_disagreements']) or 'none'}.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    return REPORT
